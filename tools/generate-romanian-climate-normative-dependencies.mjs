import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import {
  CLIMATE_DATASET_STATUSES,
  MC001_WINTER_DESIGN_TEMPERATURES_BY_ZONE,
  ROMANIAN_CLIMATE_ACQUISITION_LIST,
  ROMANIAN_CLIMATE_COVERAGE,
  ROMANIAN_CLIMATE_DATA_DOMAINS,
  ROMANIAN_CLIMATE_NORMATIVE_DEPENDENCIES,
  ROMANIAN_CLIMATE_REQUIREMENT_MATRIX,
  ROMANIAN_CLIMATE_SOURCE_INVENTORY,
  ROMANIAN_CLIMATE_ZONE_REGISTRY_VERSION
} from "../src/climate-platform/index.mjs";

const OUTPUT_JSON = resolve("validation-reference/romanian-climate-normative-dependencies.json");
const OUTPUT_MD = resolve("validation-reference/romanian-climate-normative-dependencies.md");

const sourceAudit = Object.freeze({
  officialMc0012022Pdf: "docs/Mc_001-2022_-_Metodologie_calcul_performanta_energetica_caldiri.pdf",
  visualChecks: Object.freeze([
    Object.freeze({
      sourceLocation: "MC001-2022, Figura 2.1, Monitorul Oficial p. 43",
      finding:
        "The climate-zone map legend provides winter exterior design temperatures by zones I-V: -12, -15, -18, -21 and -24 degC."
    }),
    Object.freeze({
      sourceLocation: "MC001-2022, Anexa D, Monitorul Oficial p. 597",
      finding:
        "The climate-parameter dataset is delegated to Mc001/6-2013, Partea a VI-a, approved by Order 2210/26.06.2013; EPB preprocessing is delegated to SR EN ISO 52010-1."
    })
  ]),
  recoveredOfficialSourceCandidates: Object.freeze([
    Object.freeze({
      document: "Mc001/6-2013, Partea a VI-a",
      authority: "MDLPA/MDRAP",
      officialUrl: "https://www.mdlpa.ro/userfiles/reglementari/Domeniul_XXVII/27_11_MC_001_6_2013.pdf",
      status:
        "official public PDF identified, not source-packed in repository in this milestone",
      expectedContents:
        "representative hourly years for 9 localities, monthly mean exterior parameters for 42 localities, solar data for 30 localities, winter and summer design climate tables"
    })
  ]),
  reviewedButNotDirectMc0012022Dependencies: Object.freeze([
    "SR 1907-1",
    "SR 1907-2",
    "SR 4839",
    "SR 6648-1",
    "SR 6648-2"
  ])
});

const register = {
  schema: "romanian_climate_normative_dependencies_v1",
  generatedBy: "tools/generate-romanian-climate-normative-dependencies.mjs",
  datasetStatusValues: CLIMATE_DATASET_STATUSES,
  registryVersion: ROMANIAN_CLIMATE_ZONE_REGISTRY_VERSION,
  sourceAudit,
  climateCoverage: ROMANIAN_CLIMATE_COVERAGE,
  climateSourceInventory: ROMANIAN_CLIMATE_SOURCE_INVENTORY,
  dataDomains: ROMANIAN_CLIMATE_DATA_DOMAINS,
  winterDesignTemperatureByZone: MC001_WINTER_DESIGN_TEMPERATURES_BY_ZONE,
  requirementMatrix: ROMANIAN_CLIMATE_REQUIREMENT_MATRIX,
  normativeDependencies: ROMANIAN_CLIMATE_NORMATIVE_DEPENDENCIES,
  acquisitionList: ROMANIAN_CLIMATE_ACQUISITION_LIST,
  runtimePolicy: {
    noHiddenFallbackZone: true,
    noHiddenProductionSyntheticDataset: true,
    zoneIsNotMonthlyProfile: true,
    missingDataDiagnosticRequired: true,
    certifiedImportBoundary:
      "User-supplied certified monthly climate data may run production calculations only after twelve-month completeness, units, provenance and confirmation validation."
  }
};

function table(rows, columns) {
  return [
    `| ${columns.join(" | ")} |`,
    `| ${columns.map(() => "---").join(" | ")} |`,
    ...rows.map(row => `| ${columns.map(column => String(row[column] ?? "-").replace(/\|/g, "\\|")).join(" | ")} |`)
  ].join("\n");
}

const dependencyRows = register.normativeDependencies.map(item => ({
  id: item.dependencyId,
  document: item.exactExternalDocument,
  status: item.implementationStatus,
  availability: item.availability,
  calculations: item.calculationsAffected.join(", ") || "none"
}));

const domainRows = register.dataDomains.map(item => ({
  domain: item.domainId,
  status: item.status,
  purpose: item.purpose,
  source: item.delegatedSource ?? item.implementedDataset ?? item.sourceReferences?.join("; ") ?? "-"
}));

const matrixRows = register.requirementMatrix.map(item => ({
  calculation: item.calculationId,
  requires: item.requires.join(", "),
  eligible: item.eligibleWhen,
  diagnostic: item.missingDiagnostic
}));

const acquisitionRows = register.acquisitionList.map(item => ({
  designation: item.designation,
  edition: item.edition,
  requiredFor: item.requiredFor.join(", "),
  replacement: item.substituteOwnedByProject
}));

const markdown = `# Romanian Climate Normative Dependency Register

Generated by: \`${register.generatedBy}\`.

## Status Values

- \`NORMATIVE_DATASET\`: source-backed values are bundled and versioned.
- \`USER_SUPPLIED_CERTIFIED_DATASET\`: complete certified monthly values are supplied explicitly by the user/professional.
- \`DATASET_UNAVAILABLE\`: the required source values are not bundled and cannot be silently substituted.
- \`TEST_ONLY_SYNTHETIC_DATASET\`: validation/demo data only, not production normative data.

## Source Audit

${register.sourceAudit.visualChecks.map(item => `- ${item.sourceLocation}: ${item.finding}`).join("\n")}

Official source candidate recovered:

${register.sourceAudit.recoveredOfficialSourceCandidates.map(item => `- ${item.document}, ${item.authority}: ${item.status}; ${item.officialUrl}`).join("\n")}

Reviewed but not a direct MC001-2022 dependency at this audit level: ${register.sourceAudit.reviewedButNotDirectMc0012022Dependencies.join(", ")}.

## Independent Climate Domains

${table(domainRows, ["domain", "status", "purpose", "source"])}

## Runtime Eligibility Matrix

${table(matrixRows, ["calculation", "requires", "eligible", "diagnostic"])}

## Normative Dependencies

${table(dependencyRows, ["id", "document", "status", "availability", "calculations"])}

## Acquisition List

${table(acquisitionRows, ["designation", "edition", "requiredFor", "replacement"])}

## Runtime Policy

- Climate-zone I-V selection is not a monthly climate profile.
- Wind-zone I-IV selection is metadata until a current Chapter 2/3 runtime relation consumes a wind parameter.
- Production cannot silently use \`TEST_ONLY_SYNTHETIC_DATASET\`.
- Missing monthly temperature, solar irradiation, cooling/ventilation design or degree-day datasets produce structured diagnostics and skip only the affected calculations.
- User-supplied certified datasets must carry provenance, units, twelve ordered months and explicit confirmation before they participate in fingerprints, reports and persistence.
`;

mkdirSync(dirname(OUTPUT_JSON), { recursive: true });
writeFileSync(OUTPUT_JSON, `${JSON.stringify(register, null, 2)}\n`, "utf8");
writeFileSync(OUTPUT_MD, markdown, "utf8");
